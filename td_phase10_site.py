"""NFL TD Lab | Phase 10: build and preview a mobile-first static matchup app.

Standard-library only; safely serves docs/ and NEVER exposes your project root.
Usage:
    py td_phase10_site.py --self-test
    py td_phase10_site.py --build
    py td_phase10_site.py --serve
    py td_phase10_site.py --build --input output/phase9_week_6_2026_games.json

Source: newest output/phase9_week_*_*_games.json generated by Phase 9.
Output: docs/{index.html,styles.css,app.js,manifest.webmanifest,icon.svg,sw.js,data.json}
GitHub Pages can serve /docs from main branch; do not include private files/API keys.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import re
import shutil
import sys
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / 'phase10_assets'
DOCS = ROOT / 'docs'
OUTPUT = ROOT / 'output'
PATTERN = re.compile(r'phase9_week_(\d+)_(\d{4})_games\.json$')
ASSET_NAMES = ('index.html', 'styles.css', 'app.js', 'manifest.webmanifest', 'icon.svg', 'icon-192.png', 'icon-512.png', 'sw.js')


def choose_input(file=None, output_dir=OUTPUT):
    if file is not None:
        chosen = Path(file).expanduser()
        if not chosen.is_absolute():
            chosen = ROOT / chosen
        if not chosen.is_file():
            raise FileNotFoundError(f'Could not find Phase 9 JSON: {chosen}')
        return chosen
    eligible = [p for p in output_dir.glob('phase9_week_*_*_games.json') if PATTERN.fullmatch(p.name)]
    if not eligible:
        raise FileNotFoundError(f'No Phase 9 JSON found in: {output_dir}\n'
                                'First run: py td_phase9_availability.py --season 2026')
    # Latest modification, not latest season number, because user may intentionally rerun older slates.
    return max(eligible, key=lambda p: (p.stat().st_mtime_ns, p.name))


def load_validate(path):
    with Path(path).open('r', encoding='utf-8-sig') as f:
        payload = json.load(f)
    if not isinstance(payload, dict) or payload.get('app_data_version') != 1:
        raise ValueError('Expected Phase 9 app_data_version=1 JSON. Run Phase 9 again.')
    games = payload.get('games')
    if not isinstance(games, list) or not games:
        raise ValueError('Phase 9 JSON contains no games.')
    for i, game in enumerate(games):
        if not isinstance(game, dict) or not isinstance(game.get('game'), str) or not game.get('game'):
            raise ValueError(f'Invalid game at index {i}.')
        if not isinstance(game.get('favorites'), list) or not isinstance(game.get('all_players'), list):
            raise ValueError(f'Expected favorites and all_players for game {game["game"]}.')
        if not isinstance(game.get('weather'), dict):
            raise ValueError(f'Missing weather object for game {game["game"]}.')
        for p in game['all_players']:
            if not isinstance(p, dict):
                raise ValueError('Player record must be an object.')
            prob = p.get('td_probability')
            if prob is not None:
                try: prob = float(prob)
                except (ValueError, TypeError): raise ValueError('Invalid player probability.') from None
                if not (0.0 <= prob <= 1.0):
                    raise ValueError('Player probability outside 0..1.')
    return payload


def build(source=None, assets=ASSETS, target=DOCS, quiet=False):
    input_file = choose_input(source)
    data = load_validate(input_file)
    missing = [name for name in ASSET_NAMES if not (assets / name).is_file()]
    if missing: raise FileNotFoundError(f'Missing dashboard assets: {", ".join(missing)}')
    target.mkdir(parents=True, exist_ok=True)
    for name in ASSET_NAMES:
        shutil.copyfile(assets / name, target / name)
    # Only explicit, public-facing model data goes to docs/. Never copy any API key,
    # local override CSV, model source, player raw data or historical archive.
    out = target / 'data.json'
    with out.open('w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2, allow_nan=False)
    if not quiet:
        count = sum(len(g['all_players']) for g in data['games'])
        print('\nPHASE 10 — STATIC MOBILE DASHBOARD')
        print(f'Source:  {input_file}')
        print(f'Created: {target} ({len(data["games"])} games, {count} player records)')
        print(f'Snapshot: {data.get("generated_at_utc", "UNKNOWN")}.')
        print('Status:  SAVED SNAPSHOT — no live automatic refresh or odds.')
        print('Next:    py td_phase10_site.py --serve')
        print('GitHub Pages: publish the docs/ folder on the main branch once ready.')
    return out


def serve(port=8000, directory=DOCS):
    if not (directory / 'data.json').is_file():
        raise FileNotFoundError('Site not yet built. Run: py td_phase10_site.py --build')
    handler = partial(SimpleHTTPRequestHandler, directory=str(directory))
    with ThreadingHTTPServer(('127.0.0.1', port), handler) as httpd:
        print(f'\nPREVIEW READY: http://localhost:{httpd.server_address[1]}')
        print('Open that address in a browser ON THIS COMPUTER.')
        print('Press Ctrl+C here when you want to stop the preview.')
        try: httpd.serve_forever()
        except KeyboardInterrupt: print('\nPreview stopped.')


def self_test():
    # No source change, no internet, no writes to real output/ or docs/.
    with TemporaryDirectory(prefix='td-lab-phase10-') as td:
        temp = Path(td)
        out = temp/'output'; out.mkdir()
        source = out/'phase9_week_6_2026_games.json'
        source.write_text(json.dumps({
          'app_data_version':1,'generated_at_utc':'2026-10-17T12:00:00+00:00',
          'games':[{'game':'LAC @ KC','week':6,'kickoff_utc':'2026-10-18T20:25:00+00:00',
            'weather':{'weather_flags':'STRONG WIND GUSTS','stadium':'Fixture Stadium'},
            'favorites':[{'name':'Fictional Runner A','td_probability':0.51,'status':'UNKNOWN / NOT VERIFIED'}],
            'all_players':[{'name':'Fictional Runner A','td_probability':0.51,'status':'UNKNOWN / NOT VERIFIED'}],
            'excluded':[{'name':'Fictional Runner B','td_probability':0.3,'status':'EXCLUDED: REPORTED OUT'}]}]
          }),encoding='utf8')
        target=temp/'docs'
        p=build(source=source,assets=ASSETS,target=target,quiet=True)
        data=load_validate(p)
        assert len(data['games'])==1
        assert data['games'][0]['favorites'][0]['name']=='Fictional Runner A'
        assert all((target/n).is_file() for n in ASSET_NAMES+('data.json',))
        assert 'secrets.env' not in [p.name for p in target.iterdir()]
        # Clean rejection of invalid probabilities; never accidentally publish bad data.
        data['games'][0]['all_players'][0]['td_probability']=1.4
        source.write_text(json.dumps(data),encoding='utf8')
        try: build(source=source,assets=ASSETS,target=target,quiet=True)
        except ValueError: pass
        else: raise AssertionError('Invalid player probability must fail build.')
    print('SELF-TEST PASS: JSON validation, mobile assets, safe docs export, no project files exposed.')


def main():
    parser=argparse.ArgumentParser(description='Phase 10: GitHub Pages-ready NFL TD Lab dashboard')
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--self-test',action='store_true')
    group.add_argument('--build',action='store_true')
    group.add_argument('--serve',action='store_true')
    parser.add_argument('--input',help='Optional specific Phase 9 game JSON file (for --build)')
    parser.add_argument('--port',type=int,default=8000,help='Local preview port (default 8000)')
    args=parser.parse_args()
    try:
        if args.self_test: self_test()
        elif args.build: build(args.input)
        elif args.serve:
            if not 0 <= args.port <= 65535: raise ValueError('Port must be 0 to 65535.')
            serve(args.port)
    except (FileNotFoundError,PermissionError,OSError,ValueError,json.JSONDecodeError) as exc:
        print(f'ERROR: {exc}',file=sys.stderr)
        raise SystemExit(1)

if __name__=='__main__': main()
